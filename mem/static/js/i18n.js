// fecha relativa (reemplaza los strings mock 'hace 2 h'/'ayer' del prototipo por cálculo real)
export function fechaRelativa(iso, lang) {
  if (!iso) return "";
  const d = new Date(iso), ahora = new Date();
  const segs = Math.max(0, (ahora - d) / 1000);
  const es = lang !== "en";
  if (segs < 3600) { const m = Math.max(1, Math.round(segs / 60)); return es ? `hace ${m} min` : `${m} min ago`; }
  if (segs < 86400) { const h = Math.round(segs / 3600); return es ? `hace ${h} h` : `${h} h ago`; }
  if (segs < 172800) return es ? "ayer" : "yesterday";
  if (segs < 6 * 86400) {
    const dias = es ? ["dom", "lun", "mar", "mié", "jue", "vie", "sáb"] : ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
    return dias[d.getDay()];
  }
  return d.toLocaleDateString(es ? "es-ES" : "en-US", { day: "numeric", month: "short" });
}
